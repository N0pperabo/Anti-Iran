"""Data models for GitHub Actions runs, jobs, and artifacts."""

from datetime import datetime
from enum import Enum
from typing import Dict, List, Optional, Any
from pydantic import BaseModel, Field


class RunStatus(str, Enum):
    QUEUED = "queued"
    IN_PROGRESS = "in_progress"
    COMPLETED = "completed"
    WAITING = "waiting"


class RunConclusion(str, Enum):
    SUCCESS = "success"
    FAILURE = "failure"
    CANCELLED = "cancelled"
    TIMED_OUT = "timed_out"
    SKIPPED = "skipped"
    NEUTRAL = "neutral"
    ACTION_REQUIRED = "action_required"


class WorkflowRunInfo(BaseModel):
    """Information about a GitHub Actions workflow execution run."""
    id: int
    workflow_id: int
    name: str
    head_branch: str
    status: RunStatus
    conclusion: Optional[RunConclusion] = None
    html_url: str
    created_at: str
    updated_at: str
    run_number: int
    event: str
    duration_seconds: Optional[int] = None


class JobStepInfo(BaseModel):
    """A step within a GitHub Actions Job."""
    name: str
    status: str
    conclusion: Optional[str] = None
    number: int
    started_at: Optional[str] = None
    completed_at: Optional[str] = None


class JobInfo(BaseModel):
    """A Job within a GitHub Actions Run."""
    id: int
    run_id: int
    name: str
    status: str
    conclusion: Optional[str] = None
    started_at: Optional[str] = None
    completed_at: Optional[str] = None
    steps: List[JobStepInfo] = Field(default_factory=list)


class ArtifactInfo(BaseModel):
    """An artifact generated by a workflow run."""
    id: int
    name: str
    size_in_bytes: int
    archive_download_url: str
    expired: bool = False
    created_at: str


class RepoValidationResult(BaseModel):
    """Result of validating GitHub repository and authentication token."""
    valid: bool
    owner: str
    repo: str
    is_private: bool
    default_branch: str
    has_workflows: bool
    message: str
