"""Stable selector generation, priority scoring, and ambiguity resolution."""

import re
from typing import Any, Dict, List, Optional, Tuple
from models.action_types import SelectorCandidate, SelectorPriority

# Patterns that indicate randomly generated or dynamic IDs / classes
UNSTABLE_PATTERNS = [
    re.compile(r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}", re.IGNORECASE),  # UUID
    re.compile(r"^[a-z0-9_-]{24,}$", re.IGNORECASE),                     # Long random hashes
    re.compile(r":r[0-9a-z]+:", re.IGNORECASE),                           # React 18 useId (:r0:, :r1:)
    re.compile(r"^ember\d+$", re.IGNORECASE),                             # Ember dynamic IDs
    re.compile(r"^[a-zA-Z0-9]+_[0-9a-f]{6,}$", re.IGNORECASE),           # Scoped CSS hashes (e.g. Button_a8f3b1)
    re.compile(r"^\d+$"),                                                 # Purely numeric ID
]

STABLE_DATA_ATTRIBUTES = [
    "data-testid",
    "data-test-id",
    "data-test",
    "data-qa",
    "data-cy",
    "data-automation-id",
    "data-id",
    "data-name",
]


def is_stable_identifier(val: Optional[str]) -> bool:
    """Checks whether an ID or class name appears stable rather than autogenerated."""
    if not val or not isinstance(val, str):
        return False
    val = val.strip()
    if len(val) < 1 or len(val) > 60:
        return False
    for pat in UNSTABLE_PATTERNS:
        if pat.search(val):
            return False
    return True


def clean_css_identifier(val: str) -> str:
    """Escapes characters in CSS identifier if needed."""
    return re.sub(r"([:.[\]#$,+>~])", r"\\\1", val)


def generate_candidate_selectors(
    tag: str,
    attributes: Dict[str, str],
    role: Optional[str] = None,
    text_content: Optional[str] = None,
    xpath: Optional[str] = None,
) -> List[SelectorCandidate]:
    """Generates ordered list of selector candidates from element properties."""
    candidates: List[SelectorCandidate] = []
    tag = tag.lower().strip()

    # 1. Unique stable ID
    elem_id = attributes.get("id")
    if elem_id and is_stable_identifier(elem_id):
        escaped_id = clean_css_identifier(elem_id)
        candidates.append(
            SelectorCandidate(
                selector=f"#{escaped_id}",
                priority=SelectorPriority.ID,
            )
        )

    # 2. Stable data-* attributes
    for data_attr in STABLE_DATA_ATTRIBUTES:
        if data_attr in attributes and attributes[data_attr]:
            val = attributes[data_attr].replace('"', '\\"')
            candidates.append(
                SelectorCandidate(
                    selector=f"[{data_attr}=\"{val}\"]",
                    priority=SelectorPriority.DATA_ATTR,
                )
            )

    # 3. Role and accessibility attributes
    aria_label = attributes.get("aria-label")
    if role and aria_label:
        val = aria_label.replace('"', '\\"')
        candidates.append(
            SelectorCandidate(
                selector=f"[role=\"{role}\"][aria-label=\"{val}\"]",
                priority=SelectorPriority.ROLE,
            )
        )
    elif aria_label:
        val = aria_label.replace('"', '\\"')
        candidates.append(
            SelectorCandidate(
                selector=f"{tag}[aria-label=\"{val}\"]",
                priority=SelectorPriority.ROLE,
            )
        )
    elif role:
        candidates.append(
            SelectorCandidate(
                selector=f"[role=\"{role}\"]",
                priority=SelectorPriority.ROLE,
            )
        )

    # 4. Form / Input Name attribute
    name_attr = attributes.get("name")
    if name_attr and is_stable_identifier(name_attr):
        val = name_attr.replace('"', '\\"')
        candidates.append(
            SelectorCandidate(
                selector=f"{tag}[name=\"{val}\"]",
                priority=SelectorPriority.NAME,
            )
        )

    # 4b. Text-based locator for buttons and links (Playwright has-text)
    if text_content and tag in ("button", "a", "span", "p", "h1", "h2", "h3", "h4", "li", "div"):
        clean_text = text_content.strip()
        if 2 <= len(clean_text) <= 40 and "\n" not in clean_text:
            safe_text = clean_text.replace('"', '\\"')
            candidates.append(
                SelectorCandidate(
                    selector=f"{tag}:has-text(\"{safe_text}\")",
                    priority=SelectorPriority.ROLE,
                )
            )

    # 5. Stable CSS class
    class_attr = attributes.get("class", "")
    if class_attr:
        classes = [c.strip() for c in class_attr.split() if c.strip()]
        stable_classes = [c for c in classes if is_stable_identifier(c)]
        if stable_classes:
            class_selector = f"{tag}." + ".".join(clean_css_identifier(c) for c in stable_classes[:2])
            candidates.append(
                SelectorCandidate(
                    selector=class_selector,
                    priority=SelectorPriority.CSS,
                )
            )

    # 6. Specific attribute combinations (type, placeholder, title, href)
    input_type = attributes.get("type")
    if input_type and tag == "input":
        placeholder = attributes.get("placeholder")
        if placeholder:
            p_val = placeholder.replace('"', '\\"')
            candidates.append(
                SelectorCandidate(
                    selector=f"input[type=\"{input_type}\"][placeholder=\"{p_val}\"]",
                    priority=SelectorPriority.CSS,
                )
            )
        else:
            candidates.append(
                SelectorCandidate(
                    selector=f"input[type=\"{input_type}\"]",
                    priority=SelectorPriority.CSS,
                )
            )

    # 7. XPath fallback
    if xpath:
        candidates.append(
            SelectorCandidate(
                selector=xpath if xpath.startswith("xpath=") else f"xpath={xpath}",
                priority=SelectorPriority.XPATH,
            )
        )

    return candidates


async def verify_selector_ambiguity(page: Any, selector: str) -> Tuple[int, bool]:
    """Verifies how many elements match the selector in the live page.

    Returns:
        (count, is_unique): count of matches and whether it uniquely matches exactly 1 element.
    """
    try:
        elements = await page.query_selector_all(selector)
        count = len(elements)
        return count, (count == 1)
    except Exception:
        return 0, False
